class LanguageManager(QObject):
    language_changed = Signal()

    def __init__(self, default_language: str = "zh_CN") -> None:
        super().__init__()
        self._language = default_language if default_language in TRANSLATIONS else "zh_CN"

    @property
    def language(self) -> str:
        return self._language

    def set_language(self, language: str) -> None:
        if language == self._language or language not in TRANSLATIONS:
            return
        self._language = language
        self.language_changed.emit()

    def text(self, key: str, **kwargs: Any) -> str:
        template = TRANSLATIONS[self._language].get(key, key)
        return template.format(**kwargs)


SUPPORTED_LANGUAGES = [("zh_CN", "language.zh_CN"), ("en_US", "language.en_US")]
